#!/usr/bin/env node
/* Writes the complete one-shot setup SQL (tables + site settings + the care
   homes) so it can be pasted into Supabase → SQL Editor → Run — no database
   password on a command line.   Usage:  npm run setup-sql
   Safe to run more than once: nothing is dropped or overwritten. */

const fs = require('fs');
const path = require('path');
process.env.DATABASE_URL = ''; // only the defaults are needed, never a connection
const db = require('../db.js');

const q = (v) => (v === null || v === undefined ? 'null' : "'" + String(v).replace(/'/g, "''") + "'");
const arr = (list) => (!list || !list.length ? "'{}'" : 'array[' + list.map(q).join(', ') + ']::text[]');
const nm = (v) => (v === null || v === undefined || v === '' ? 'null' : Number(v));

const out = [
  '-- =============================================================',
  '-- Venza Care UK — one-shot database setup',
  '-- Paste this whole file into Supabase → SQL Editor → Run.',
  '-- Safe to run more than once: nothing is dropped or overwritten.',
  '-- Generated by scripts/emit-setup-sql.js — edit sql/schema.sql instead.',
  '-- =============================================================',
  '',
  fs.readFileSync(path.join(__dirname, '..', 'sql', 'schema.sql'), 'utf8').trim(),
  '',
  '-- ---------- Site settings ----------',
  "insert into settings (key, value) values ('site', " + q(JSON.stringify(db.DEFAULT_SITE)) + '::jsonb) on conflict (key) do nothing;',
  '',
  '-- ---------- Care homes ----------',
];
db.DEFAULT_HOMES.forEach((h, i) => {
  out.push(
    'insert into homes (id, name, town, postcode, region, lat, lng, beds, cqc,\n' +
    '                   care_types, specialisms, blurb, dementia_note, photo, gallery, sort_order)\n' +
    'values (' + [q(h.id), q(h.name), q(h.town), q(h.postcode), q(h.region), nm(h.lat), nm(h.lng), nm(h.beds), q(h.cqc)].join(', ') + ',\n' +
    '        ' + [arr(h.careTypes), arr(h.specialisms), q(h.blurb), q(h.dementiaNote), q(h.photo), arr(h.gallery), i].join(', ') + ')\n' +
    'on conflict (id) do nothing;',
    ''
  );
});
out.push('-- No vacancies or staff accounts are created. Sign in with the emergency');
out.push('-- owner login (ADMIN_USER / ADMIN_PASS) and invite people from the staff hub.');
fs.writeFileSync(path.join(__dirname, '..', 'sql', 'setup.sql'), out.join('\n') + '\n');
console.log('Wrote sql/setup.sql');
